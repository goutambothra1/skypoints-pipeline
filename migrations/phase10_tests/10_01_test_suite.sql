
USE DATABASE SKYPOINTS_DB; USE WAREHOUSE WH_SKYPOINTS;

-- Tests 01-08: Date parsing, field defaults, DQ flags
SELECT test_id, description,
       IFF(actual IS NULL AND expected IS NULL,'PASS', IFF(actual=expected,'PASS','FAIL')) AS status,
       expected, actual
FROM (
    SELECT '01' test_id,'DOB leading-zero fix Jacob 3051985→1985-03-05' description,'1985-03-05' expected, DOB::VARCHAR actual FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='223461'
    UNION ALL SELECT '02','Invalid DOB→NULL Sameer 13/13/1952', NULL, DOB::VARCHAR FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='100003'
    UNION ALL SELECT '03','Invalid enroll date→NULL Jonnathan 2021-13-13', NULL, ENROLLMENT_DATE::VARCHAR FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='200002'
    UNION ALL SELECT '04','Literal NULL string→SQL NULL Mike DOB', NULL, DOB::VARCHAR FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='200001'
    UNION ALL SELECT '05','Unpadded Canada date 6152022→2022-06-15 Sam', '2022-06-15', ENROLLMENT_DATE::VARCHAR FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='300001'
    UNION ALL SELECT '06','Invalid tier BRZ→DQ_STATUS=WARN Jacob', 'WARN', DQ_STATUS FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='223461'
    UNION ALL SELECT '07','DQ_REASON=INVALID_TIER_CODE Jacob', 'INVALID_TIER_CODE', DQ_REASON FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='223461'
    UNION ALL SELECT '08','Empty Agent_Name→NULL Ravi', NULL, AGENT_NAME::VARCHAR FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='223458'
) ORDER BY test_id;

-- Tests 09-16: Country move, dedup, JSON quarantine, country normalisation
SELECT test_id, description,
       IFF(actual IS NULL AND expected IS NULL,'PASS', IFF(actual=expected,'PASS','FAIL')) AS status,
       expected, actual
FROM (
    SELECT '09' test_id,'Nora absent TABLE_CANADA' description,'0' expected,(SELECT COUNT(*)::VARCHAR FROM SKYPOINTS_DB.CORE.TABLE_CANADA WHERE MEMBER_ID='223460') actual
    UNION ALL SELECT '10','Nora present TABLE_USA','1',(SELECT COUNT(*)::VARCHAR FROM SKYPOINTS_DB.CORE.TABLE_USA WHERE MEMBER_ID='223460')
    UNION ALL SELECT '11','Ravi single row in STG after dedup','1',(SELECT COUNT(*)::VARCHAR FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='223458')
    UNION ALL SELECT '12','RX10092 PENDING→COMPLETED','COMPLETED',(SELECT STATUS FROM SKYPOINTS_DB.CORE.REDEMPTIONS_FLAT WHERE TXN_ID='RX10092')
    UNION ALL SELECT '13','RX10093 orphan 999999 quarantined','ORPHAN_MEMBER',(SELECT QUARANTINE_REASON FROM SKYPOINTS_DB.CORE.REDEMPTIONS_QUARANTINE WHERE TXN_ID='RX10093')
    UNION ALL SELECT '14','RX10094 INVALID_STATUS|NEG_OR_ZERO_MILES quarantined','INVALID_STATUS|NEG_OR_ZERO_MILES',(SELECT QUARANTINE_REASON FROM SKYPOINTS_DB.CORE.REDEMPTIONS_QUARANTINE WHERE TXN_ID='RX10094')
    UNION ALL SELECT '15','AU normalised to AUS via COUNTRY_MAP','AUS',(SELECT COUNTRY FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='223461')
    UNION ALL SELECT '16','STALE_MEMBER=Y when LAST_FLIGHT_DATE IS NULL','Y',(SELECT STALE_MEMBER FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='223461')
) ORDER BY test_id;

-- Tests 17-20: AGE, DQ reconciliation, V_ALL_MEMBERS, MEMBER_TYPE
SELECT test_id, description,
       IFF(actual IS NULL AND expected IS NULL,'PASS', IFF(actual=expected,'PASS','FAIL')) AS status,
       expected, actual
FROM (
    SELECT '17' test_id,'Elena AGE birthday-aware between 30-60' description,'TRUE' expected,
           (SELECT IFF(AGE BETWEEN 30 AND 60,'TRUE','FALSE') FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='223457') actual
    UNION ALL SELECT '18','DQ row-count reconciliation PASS','PASS',
           (SELECT STATUS FROM SKYPOINTS_DB.DQ.DQ_RESULTS WHERE RULE_ID='RECONCILE_ROW_COUNT' ORDER BY RUN_TS LIMIT 1)
    UNION ALL SELECT '19','V_ALL_MEMBERS returns all 14 members','14',
           (SELECT COUNT(*)::VARCHAR FROM SKYPOINTS_DB.CORE.V_ALL_MEMBERS)
    UNION ALL SELECT '20','India Individual=I stored in MEMBER_TYPE Vikas','I',
           (SELECT MEMBER_TYPE FROM SKYPOINTS_DB.STG.MEMBER WHERE MEMBER_ID='100001')
) ORDER BY test_id;
